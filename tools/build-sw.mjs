// Regenerates sw.js with the full precache list and a content hash as the cache version.
// Run after changing any app file:  node tools/build-sw.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'vendor', 'icons'];
const files = [];
const walk = (p) => statSync(p).isDirectory() ? readdirSync(p).forEach((f) => walk(join(p, f))) : files.push(relative(root, p));
include.forEach((p) => walk(join(root, p)));
files.sort();
const hash = createHash('sha256');
files.forEach((f) => hash.update(f).update(readFileSync(join(root, f))));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by tools/build-sw.mjs. Do not edit by hand.
const CACHE = 'vigor-${version}';
const ASSETS = ${JSON.stringify(['./', ...files.map((f) => './' + f)], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });

// Cache-first for app files (works fully offline); network fallback for anything else.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const cached = await caches.match(req, { ignoreSearch: true });
    if (cached) return cached;
    try {
      const res = await fetch(req);
      if (res.ok) (await caches.open(CACHE)).put(req, res.clone());
      return res;
    } catch {
      if (req.mode === 'navigate') return caches.match('./index.html');
      throw new Error('offline');
    }
  })());
});
`;
writeFileSync(join(root, 'sw.js'), sw);
console.log(`sw.js → ${CACHE_NAME(version)} with ${files.length + 1} assets`);
function CACHE_NAME(v) { return 'vigor-' + v; }
